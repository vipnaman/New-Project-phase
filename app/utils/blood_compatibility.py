BLOOD_COMPATIBILITY = {
    "O-": ["O-"],
    "O+": ["O-", "O+"],
    "A-": ["O-", "A-"],
    "A+": ["O-", "O+", "A-", "A+"],
    "B-": ["O-", "B-"],
    "B+": ["O-", "O+", "B-", "B+"],
    "AB-": ["O-", "A-", "B-", "AB-"],
    "AB+": ["O-", "O+", "A-", "A+", "B-", "B+", "AB-", "AB+"],
}


def can_donate_to(donor_group, recipient_group):
    return recipient_group in BLOOD_COMPATIBILITY.get(donor_group, [])


def compatible_donors_for_request(blood_group):
    return BLOOD_COMPATIBILITY.get(blood_group, [])
